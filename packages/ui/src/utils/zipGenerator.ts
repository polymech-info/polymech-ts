
import JSZip from 'jszip';
import { saveAs } from 'file-saver';
import { PostRendererProps } from '@/modules/posts/views/types';

// Simplified types for the generator
interface Post {
    title: string;
    description: string;
    [key: string]: any;
}

interface MediaItem {
    id: string;
    image_url: string;
    title?: string;
    description?: string;
    type?: string;
    [key: string]: any;
}

export const generateOfflineZip = async (
    post: Post | undefined,
    mediaItems: MediaItem[],
    authorName: string,
    onProgress?: (percent: number) => void
) => {
    const zip = new JSZip();
    const imagesFolder = zip.folder("images");

    // 1. Fetch Images and add to ZIP
    const totalItems = mediaItems.length;
    let processedCount = 0;

    const itemsWithLocalPaths = await Promise.all(mediaItems.map(async (item, index) => {
        try {
            // Determine file extension
            const url = item.image_url;
            const extension = url.split('.').pop()?.split('?')[0] || 'jpg';
            const filename = `image_${index + 1}.${extension}`;

            // Allow for cross-origin fetches if needed, though usually same-origin or CORS enabled
            const response = await fetch(url);
            const blob = await response.blob();

            if (imagesFolder) {
                imagesFolder.file(filename, blob);
            }

            processedCount++;
            if (onProgress) {
                onProgress((processedCount / totalItems) * 80); // 80% for fetching
            }

            return {
                ...item,
                localPath: `images/${filename}`
            };
        } catch (error) {
            console.error(`Failed to fetch image ${item.image_url}`, error);
            return {
                ...item,
                localPath: item.image_url // Fallback to remote URL if fetch fails
            };
        }
    }));

    // 2. Generate HTML
    const htmlContent = `
<!DOCTYPE html>
<html>
<head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>${post?.title || 'PhotoShare Gallery'}</title>
    <style>
        body { font-family: system-ui, -apple-system, sans-serif; max-width: 800px; margin: 0 auto; padding: 20px; color: #333; line-height: 1.6; }
        h1 { margin-bottom: 0.5em; }
        .metadata { color: #666; margin-bottom: 2em; border-bottom: 1px solid #eee; padding-bottom: 1em; }
        .gallery-item { margin-bottom: 4em; }
        img { max-width: 100%; height: auto; border-radius: 8px; box-shadow: 0 4px 6px rgba(0,0,0,0.1); margin-bottom: 1em; display: block; }
        .item-title { font-size: 1.25em; font-weight: bold; margin-bottom: 0.5em; }
        .item-desc { color: #555; }
        .video-note { background: #f0f9ff; padding: 1em; border-radius: 8px; margin-bottom: 1em; color: #0369a1; }
    </style>
</head>
<body>
    <div class="header">
        <h1>${post?.title || 'Gallery'}</h1>
        ${post?.description ? `<p>${post.description}</p>` : ''}
        <div class="metadata">
            By ${authorName}
        </div>
    </div>

    <div class="gallery">
        ${itemsWithLocalPaths.map(item => `
            <div class="gallery-item">
                ${item.type?.includes('video') || item.image_url.includes('tiktok')
            ? `<div class="video-note">Video content not included in offline zip. <a href="${item.image_url}" target="_blank">View Online</a></div>`
            : `<img src="${item.localPath}" alt="${item.title || ''}" loading="lazy" />`
        }
                
                ${item.title && item.title !== post?.title ? `<div class="item-title">${item.title}</div>` : ''}
                ${item.description ? `<div class="item-desc">${item.description}</div>` : ''}
            </div>
        `).join('')}
    </div>

    <div class="footer">
        <p>Generated by PolyMech PhotoShare</p>
    </div>
</body>
</html>
    `;

    zip.file("index.html", htmlContent);

    // 3. Generate ZIP blob
    if (onProgress) onProgress(90);

    const content = await zip.generateAsync({ type: "blob" });

    if (onProgress) onProgress(100);

    // 4. Trigger Download
    const safeTitle = (post?.title || 'gallery').replace(/[^a-z0-9]/gi, '_').toLowerCase();
    saveAs(content, `${safeTitle}.zip`);
};
